import {readFileSync,writeFileSync,mkdirSync,cpSync,existsSync} from 'node:fs';
import {join} from 'node:path';
const assets={};
const types={'index.html':'text/html; charset=utf-8','styles.css':'text/css; charset=utf-8','app.js':'text/javascript; charset=utf-8','domain.js':'text/javascript; charset=utf-8','favicon.svg':'image/svg+xml','manifest.webmanifest':'application/manifest+json'};
for(const [file,type] of Object.entries(types))assets['/'+file]={body:readFileSync(join('public',file),'utf8'),type};
assets['/']=assets['/index.html'];
const domain=readFileSync('public/domain.js','utf8').replaceAll('export ','');
const billing=readFileSync('billing-core.mjs','utf8').replaceAll('export ','');
const googleAuth=readFileSync('google-auth.mjs','utf8').replaceAll('export ','');
const worker=readFileSync('worker.mjs','utf8').replace("import { estimateTotals, statuses } from './public/domain.js';",'').replace("import { MONTHLY_PRICE, nextBillingDate, entitlement, validateBillingReturn, tossRequest, lookupTossOrder, verifyCharge, encryptBillingKey, decryptBillingKey } from './billing-core.mjs';",'').replace("import { cookie, digest, verifyGoogleIdToken, sessionUser, sessionCookie, clearSessionCookie } from './google-auth.mjs';",'');
mkdirSync('dist/server',{recursive:true});mkdirSync('dist/.openai',{recursive:true});
writeFileSync('dist/server/index.js',`const ASSETS=${JSON.stringify(assets)};\n${domain}\n${billing}\n${googleAuth}\n${worker}`);
cpSync('.openai/hosting.json','dist/.openai/hosting.json');
if(!existsSync('drizzle'))throw new Error('Generate database migrations first.');
cpSync('drizzle','dist/drizzle',{recursive:true});
const source=readFileSync('dist/server/index.js','utf8');
const mod=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
if(typeof mod.default?.fetch!=='function')throw new Error('Worker fetch export missing');
console.log('Built and verified Cloudflare Worker, private assets, and migrations.');
